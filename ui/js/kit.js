// The optional project-folder input. `attrs` wires it up: a data-input
// binding in live dialogs, a form field name in submitted ones.
export const folderField = (id, value, attrs) => `
<div class="field">
  <label for="${id}">Project folder <span class="muted">(optional)</span></label>
  <input id="${id}" ${attrs} value="${esc(value)}" placeholder="C:\\path\\to\\project" autocomplete="off" spellcheck="false">
</div>`;

// Name suggestions for a project-name input (list="<id>").
export const projectNames = (projects, id) =>
  `<datalist id="${id}">${projects.map((p) => `<option value="${esc(p.name)}"></option>`).join('')}</datalist>`;

export const toastsView = (toasts) =>
  toasts
    .map(
      (t) => `
<div class="toast toast-${t.kind}">
  <span class="toast-msg">${esc(t.msg)}</span>
  ${t.detail ? `<span class="toast-detail mono">${esc(t.detail)}</span>` : ''}
</div>`
    )
    .join('');
